using System.ComponentModel.DataAnnotations;
using ApiDot.Server.Enums;

namespace ApiDot.Server.Data.Entities;

public class AgentDevice
{
    public Guid Id { get; set; } = Guid.NewGuid();

    [MaxLength(200)]
    public string Name { get; set; } = string.Empty;

    [MaxLength(64)]
    public string TokenHash { get; set; } = string.Empty;

    [MaxLength(32)]
    public string TokenPrefix { get; set; } = string.Empty;

    public DateTime CreatedAtUtc { get; set; } = DateTime.UtcNow;

    public DateTime? LastConnectedAtUtc { get; set; }

    [MaxLength(64)]
    public string? LastConnectedIp { get; set; }

    [MaxLength(256)]
    public string? LastConnectedHostname { get; set; }

    [MaxLength(128)]
    public string? LastConnectedOs { get; set; }

    [MaxLength(64)]
    public string? AgentVersion { get; set; }

    public bool IsRevoked { get; set; } = false;

    /// <summary>
    /// Machine identifier generated by the client and reused across logins. Legacy rows
    /// created before the unified credential have no key.
    /// </summary>
    [MaxLength(64)]
    public string? DeviceKey { get; set; }

    /// <summary>
    /// Capabilities accepted for this device. Legacy rows are backfilled to <see cref="DeviceScope.Ws"/>.
    /// </summary>
    public DeviceScope Scopes { get; set; } = DeviceScope.Ws;

    /// <summary>Null means the token does not expire.</summary>
    public DateTime? ExpiresAtUtc { get; set; }

    /// <summary>Last authenticated REST request, refreshed at most once per hour.</summary>
    public DateTime? LastUsedAtUtc { get; set; }

    public Guid? UserId { get; set; }
    public User? User { get; set; }
}
